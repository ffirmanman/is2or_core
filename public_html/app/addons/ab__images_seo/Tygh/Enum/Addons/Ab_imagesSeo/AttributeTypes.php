namespace Tygh\Enum\Addons\Ab_imagesSeo;

class AttributeTypes {

const ALT = 'A';

const TITLE = 'T';

const IMAGE_NUMBER = 'N';

public static function getList(array $exclude = []) {
$types = [
self::ALT => self::ALT,
self::TITLE => self::TITLE,
self::IMAGE_NUMBER => self::IMAGE_NUMBER,
];
foreach ($exclude as $_tmp) {
unset($types[$_tmp]);
}
return $types;
}

public static function getAll()
{
return self::getList();
}
}